#!/usr/bin/env node
// Builds src/app/dashboard/influencers/redesign-scope.css from the full-app
// redesign stylesheet (src/app/redesign.css on branch redesign/app-v2) so the
// Influencers page can ship the redesign ahead of the rest of the app.
//
//   git show "origin/redesign/app-v2:src/app/redesign.css" > /tmp/redesign.css
//   node scripts/scope-redesign-css.mjs /tmp/redesign.css
//
// Keeps part 1 (tokens) and part 3 (shared components), drops part 2 (the new
// pm3- shell), and prefixes EVERY selector with `.pm-rd` so nothing outside
// the Influencers page changes. Delete this script and the generated file when
// the full redesign merges.

import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/scope-redesign-css.mjs <path to redesign.css>");
  process.exit(1);
}
const out = path.resolve("src/app/dashboard/influencers/redesign-scope.css");
const root = postcss.parse(fs.readFileSync(src, "utf8"), { from: src });

// Part boundaries come from the section comments in redesign.css.
let shellStart = Infinity;
let partThreeStart = Infinity;
root.walkComments((c) => {
  if (/-{3,}\s*2\. shell/.test(c.text)) shellStart = c.source.start.line;
  if (/-{3,}\s*3\. shared components/.test(c.text)) partThreeStart = c.source.start.line;
});
if (!Number.isFinite(shellStart) || !Number.isFinite(partThreeStart)) {
  throw new Error("could not find the part 2 / part 3 markers in redesign.css");
}
const inShell = (node) => {
  const l = node.source.start.line;
  return l >= shellStart && l < partThreeStart;
};

const ROOTS = new Set([':root', ':root[data-theme="light"]', ":root[data-theme]"]);
const scopeSel = (sel) => {
  const t = sel.trim();
  if (t === "html") return null; // the page wrapper carries the background
  if (t === "body" || ROOTS.has(t)) return ".pm-rd";
  if (t.includes("pm3-")) return null; // new shell only
  return `.pm-rd ${t}`;
};

root.walkRules((rule) => {
  if (inShell(rule)) {
    // The shell's responsive gutter is read by .pm-page padding (part 3): keep
    // just that token, scoped.
    const isRootTok = rule.selectors.every((s) => ROOTS.has(s.trim()));
    const gutter = rule.nodes.filter((n) => n.type === "decl" && n.prop === "--pm3-gutter");
    if (rule.parent.type === "atrule" && isRootTok && gutter.length) {
      rule.selector = ".pm-rd";
      rule.nodes.filter((n) => !gutter.includes(n)).forEach((n) => n.remove());
      return;
    }
    rule.remove();
    return;
  }
  const sels = [...new Set(rule.selectors.map(scopeSel).filter(Boolean))];
  if (!sels.length) {
    rule.remove();
    return;
  }
  rule.selectors = sels;
});

// Drop shell comments and any now-empty at-rules.
root.walkComments((c) => {
  if (inShell(c)) c.remove();
});
root.walkAtRules((a) => {
  if (!a.nodes || a.nodes.length === 0) a.remove();
});

// The redesign fonts (Assistant + JetBrains Mono) are loaded only for this
// page under their own variable names (see ./fonts.ts), so the root
// --font-sans / --font-mono of every other page stay untouched.
root.walkDecls((d) => {
  d.value = d.value.replace(/var\(--font-sans\)/g, "var(--font-rd-sans)").replace(/var\(--font-mono\)/g, "var(--font-rd-mono)");
});

// Sanity: every selector must be scoped.
const bad = [];
root.walkRules((r) => {
  if (r.parent.type === "atrule" && /keyframes/.test(r.parent.name)) return;
  r.selectors.forEach((s) => {
    if (!s.startsWith(".pm-rd")) bad.push(s);
  });
});
if (bad.length) throw new Error(`unscoped selectors: ${bad.join(", ")}`);

const header = `/* ============================================================
   GENERATED by scripts/scope-redesign-css.mjs. Do not edit by hand.
   Source: src/app/redesign.css on branch redesign/app-v2 (parts 1 + 3;
   part 2, the pm3- shell, is dropped). Every selector is scoped to .pm-rd,
   the wrapper around the Influencers page, so loading this file globally
   changes no other screen. DELETE this file, the dark appendix below and
   the script when the full redesign merges into main.
   ============================================================ */
`;

// main still supports dark mode (prefers-color-scheme / data-theme="dark");
// the redesign has no dark palette yet, so inside .pm-rd dark mode keeps
// main's dark colours and only adds the three tokens the redesign introduced.
const DARK = `--pm-app:#141012; --pm-card:#1D181A; --pm-card2:#231D20; --pm-card3:#2A2326;
  --pm-border:#352D30; --pm-line:#2B2427;
  --pm-ink:#F3EEEF; --pm-ink2:#DDD4D7; --pm-muted:#BBB0B4; --pm-hint:#877C80;
  --pm-brand:#E0525A; --pm-brand-deep:#C9414A; --pm-brand-ink:#1D0B0D; --pm-brand-soft:#3A1C1F; --pm-brand-line:#5C2A2F;
  --pm-green:#4CB985; --pm-green-soft:#15301F;
  --pm-gold:#E6A04A;  --pm-gold-soft:#3A2913;
  --pm-terra:#EF6D51; --pm-terra-soft:#3D1D17;
  --pm-blue:#4FC0D6;  --pm-blue-soft:#12323A;
  --pm-cyan:#4FC0D6;  --pm-cyan-soft:#12323A;
  --pm-sun:#FFD23F;   --pm-sun-soft:#3A3113; --pm-sun-ink:#FFD23F;
  --pm-orange:#F0843F; --pm-orange-soft:#3B2416;
  --pm-shadow:0 1px 2px rgba(0,0,0,.4),0 8px 28px rgba(0,0,0,.35);
  --pm-shadow-pop:0 24px 60px rgba(0,0,0,.55),0 2px 6px rgba(0,0,0,.4);
  color-scheme:dark;`;
const dark = `
/* ---------- dark mode (hand-kept, see generator) ---------- */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) .pm-rd {
  ${DARK}
  }
}
:root[data-theme="dark"] .pm-rd {
  ${DARK}
}
`;

fs.writeFileSync(out, header + root.toString().replace(/^\s+/, "") + "\n" + dark);
console.log(`wrote ${path.relative(process.cwd(), out)}`);
